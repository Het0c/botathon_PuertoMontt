import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:1420');
await page.getByText('Una mirada a toda la red',{exact:true}).waitFor();
await page.getByText('SQLite conectado',{exact:true}).waitFor();
await page.getByText('ATENCIONES PLANIFICADAS',{exact:true}).waitFor();
mkdirSync('work/screenshots',{recursive:true});
await page.screenshot({path:'work/screenshots/resumen.png',fullPage:true});
await page.getByRole('button',{name:'Ver detalle de Puerto Montt'}).click();
await page.getByRole('textbox',{name:'Buscar profesional o cargo'}).fill('PRO-009');
await page.getByRole('combobox').last().selectOption('2026-01');
const initial = await page.locator('.people-card tbody tr').innerText();
await page.getByRole('button',{name:'Carga de reportes BUK'}).click();
const inputs=page.locator('input[type=file]');
await inputs.nth(0).setInputFiles('examples/BUK_cambio_julio.xlsx');
await page.getByLabel('Reutilizar el SIC de la última versión válida').check();
await page.getByRole('button',{name:'Validar y publicar',exact:true}).click();
await page.locator('.import-result').waitFor();
await inputs.nth(0).setInputFiles('examples/BUK_invalido.xlsx');
await page.getByRole('button',{name:'Validar y publicar',exact:true}).click();
await page.getByRole('alert').waitFor();
if (!(await page.getByRole('alert').innerText()).includes('duplicados')) throw new Error('Faltó validar duplicados');
await page.screenshot({path:'work/screenshots/rechazo.png',fullPage:true});
await page.getByRole('button',{name:'Dotación y metas',exact:true}).click();
const after=await page.locator('.people-card tbody tr').innerText();
if(initial!==after) throw new Error('Cambió enero al ingresar un cambio de julio');
await page.getByRole('combobox').last().selectOption('2026-07');
const july=await page.locator('.people-card tbody tr').innerText();
if (!july.includes('138')) throw new Error('Julio no refleja las 30 h semanales');
await page.getByRole('button',{name:'Versiones y trazabilidad',exact:true}).click();
await page.getByText('Rechazada',{exact:true}).first().waitFor();
const versionRows=await page.locator('tbody tr').count();
const downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Exportar plan',exact:true}).click();
const file=await downloadPromise;
if(!(file.suggestedFilename().endsWith('.csv'))) throw new Error('Falló la exportación');
await page.getByRole('button',{name:'Resumen nacional',exact:true}).click();
await page.getByRole('button',{name:'Limpiar filtros'}).click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'work/screenshots/movil.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
if(overflow) throw new Error('La página desborda en móvil');
if(errors.length) throw new Error(errors.join('\n'));
await browser.close();
console.log(JSON.stringify({status:'ok',january_preserved:true,july_changed:true,invalid_rejected:true,csv_download:true,mobile_no_overflow:true,history_rows:versionRows,page_errors:errors.length}));
